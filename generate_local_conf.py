#!/usr/bin/env python3
"""Part 2: turn an openbmc-image-builder spec JSON into a local.conf fragment.

Pinned in Part 2 (verified against the fetched trees, see part2-mapping.md):
- MACHINE: asserted, presets evb-ast2500 / evb-ast2600 (upstream meta-evb)
  and ast2700-dcscm (ASPEED SDK meta-aspeed-sdk). No evb-ast2700 preset:
  no such Yocto machine conf was found.
- Services: IMAGE_FEATURES:append with obmc-bmcweb (Redfish via bmcweb),
  obmc-net-ipmi + obmc-host-ipmi (IPMI), ssh-server-dropbear (SSH),
  obmc-webui (Web UI). All four are already in the default
  obmc-phosphor-image IMAGE_FEATURES, so the append makes the intent
  explicit; it does not add packages beyond the default image.
  Deselecting a service is NOT translated into a removal: the removal
  mapping is unpinned and the default image would still include it,
  so the fragment emits a WARNING instead of a fake removal.

NOT pinned, by design (no local.conf variable was found in either tree):
- Hostname and network (DHCP / static IP) are runtime configuration in
  OpenBMC, managed after boot by phosphor-networkd
  (xyz.openbmc_project.Network), not by a local.conf assignment.
  The fragment therefore records them as commented runtime notes only.
  No HOSTNAME / DHCP / static-IP variable is invented here.
- SSH key provisioning: no build-time local.conf variable was found for
  injecting an authorized key. The fragment records only a public-key
  path reference, never a pasted key, and key provisioning stays a
  post-boot step (TODO).
- Image artifact kind (.static.mtd / .tar) selects which build artifact
  to use downstream (QEMU / flash); it is not a local.conf assignment.
  Upstream static.inc already produces mtd-static, mtd-static-tar and
  mtd-static-alltar.

No build is run, no image is verified by this script.

Usage:
    python3 generate_local_conf.py spec.json [-o out.conf]
"""
import argparse
import json
import sys

VERIFIED_PRESETS = {"evb-ast2500", "evb-ast2600", "ast2700-dcscm"}

# Form service name -> IMAGE_FEATURES tokens (Part 2 mapping, see part2-mapping.md).
SERVICE_FEATURES = {
    "redfish": ["obmc-bmcweb"],
    "ipmi": ["obmc-net-ipmi", "obmc-host-ipmi"],
    "ssh": ["ssh-server-dropbear"],
    "webui": ["obmc-webui"],
}
ALL_SERVICES = ["redfish", "ipmi", "ssh", "webui"]


def fragment(spec: dict) -> str:
    machine = (spec.get("machine") or "").strip()
    if not machine:
        raise ValueError("spec is missing a machine name")
    net = spec.get("network") or {}
    mode = net.get("mode", "dhcp")
    services = spec.get("requested_services") or []
    lines = [
        "# OpenBMC build fragment — generated by Part 2 GUI (spec v1)",
        "# Pinned mappings are in part2-mapping.md; unpinned items stay commented, never invented.",
        f'MACHINE = "{machine}"',
    ]
    if machine not in VERIFIED_PRESETS:
        lines.append(
            "# WARNING: machine is not a verified preset in the fetched tree. "
            "Confirm a matching machine conf exists."
        )
    # Services: real IMAGE_FEATURES assignment for the selected services.
    selected_features = []
    for svc in ALL_SERVICES:
        if svc in services:
            selected_features.extend(SERVICE_FEATURES[svc])
    if selected_features:
        lines.append(
            'IMAGE_FEATURES:append = " ' + " ".join(selected_features) + ' "'
        )
    lines.append(
        "# NOTE: the services above are already in the default "
        "obmc-phosphor-image IMAGE_FEATURES; this append makes the "
        "selection explicit for a custom image recipe."
    )
    deselected = [svc for svc in ALL_SERVICES if svc not in services]
    if deselected:
        lines.append(
            "# WARNING: deselected service(s) "
            + ", ".join(deselected)
            + " are NOT removed by this fragment. "
            "The removal mapping is unpinned, and the default "
            "obmc-phosphor-image would still include them. "
            "Do not ship this fragment as a service-excluded image "
            "until removal is verified with a real build."
        )
    # Hostname / network: runtime configuration, commented only.
    lines.append(
        f"# RUNTIME (not a build setting): hostname = {spec.get('hostname')} "
        "— set after first boot via phosphor-networkd "
        "(Redfish / D-Bus xyz.openbmc_project.Network). "
        "No local.conf hostname variable was found in either tree."
    )
    net_note = f"network mode = {mode}"
    if mode == "static":
        net_note += f", static_ip = {net.get('static_ip')}, gateway = {net.get('gateway')}"
    lines.append(
        f"# RUNTIME (not a build setting): {net_note} "
        "— apply after first boot via phosphor-networkd; "
        "no local.conf DHCP/static-IP variable was found in either tree. "
        "For a reproducible fleet setting, ship a systemd .network file "
        "in a custom layer (future work, not generated here)."
    )
    # Image artifact kind: downstream selection, not a build assignment.
    lines.append(
        f"# ARTIFACT (downstream use only): image_artifact_kind = "
        f"{spec.get('image_artifact_kind')} "
        "— upstream static.inc produces mtd-static / mtd-static-tar / "
        "mtd-static-alltar; pick the matching file from "
        "tmp/deploy/images/<machine>/ after the build."
    )
    key_path = spec.get("ssh_public_key_path")
    if key_path:
        lines.append(
            f"# TODO (key provisioning, post-boot): SSH public key path "
            f"reference = {key_path} (never a pasted key, never a private "
            "key). No build-time authorized-key variable was found in "
            "either tree."
        )
    lines.append(
        "# NOT DONE in Part 2: real bitbake build, QEMU boot run, "
        "service-removal verification, layer-drift maintenance, "
        "hostname/network runtime provisioning automation."
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("-o", "--output")
    args = ap.parse_args()
    with open(args.spec, encoding="utf-8") as fh:
        spec = json.load(fh)
    try:
        out = fragment(spec)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(out)
    else:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
